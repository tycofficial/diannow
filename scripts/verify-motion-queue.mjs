import assert from 'node:assert/strict';
import {MotionQueue} from '../web/gestures.mjs';
const sent=[];const queue=new MotionQueue((event,fast=false)=>sent.push({event,fast}));
queue.emit({type:'touch',phase:'down',x:0,y:0});
for(let i=1;i<=500;i++)queue.emit({type:'touch',phase:'move',x:i/500,y:.2});
assert.equal(sent.length,1);queue.flush();assert.equal(sent.length,2);
assert.equal(sent[1].fast,true);assert.equal(sent[1].event.x,1);
queue.emit({type:'touch',phase:'up',x:1,y:.2});
assert.equal(sent[2].fast,false);assert(sent[2].event.touchSeq>sent[1].event.touchSeq);
queue.emit({type:'touch',phase:'down',x:.5,y:.5});
assert(sent[3].event.gesture>sent[0].event.gesture);
queue.emit({type:'touch',phase:'move',x:.6,y:.5});queue.emit({type:'touch',phase:'cancel',x:.6,y:.5});
const count=sent.length;queue.flush();assert.equal(sent.length,count,'Cancel must discard unsent motion');
queue.reset();sent.length=0;
for(let i=0;i<100;i++)queue.emit({type:'relative',dx:2,dy:-1});
queue.flush();assert.equal(sent.length,1);assert.equal(sent[0].event.totalX,200);assert.equal(sent[0].event.dy,-100);
queue.emit({type:'relative',dx:5,dy:7});queue.emit({type:'button',button:0,down:true});
assert.equal(sent[1].fast,true);assert.deepEqual(sent[2].event.relativeSnapshot,{totalX:205,totalY:-93,seq:101});
assert.equal(sent[2].fast,false);queue.reset();queue.flush();assert.equal(sent.length,3);
console.log('Verified latest-only touch motion, gesture boundaries, cumulative trackpad recovery and reset.');
